module CocoaSourceData

using FermentModels: COCOA_STATES, COCOA_PARAMETERS
using SHA
using TOML
include("verify_cocoa.jl")

const ROOT = normpath(joinpath(@__DIR__, ".."))
const TRIALS = (:camu, :box1, :box2)
const DRIVERS = (camu="camu.R", box1="p_box1.R", box2="p_box2.R")

function cocoa_trial(experiment::Symbol; root=ROOT)
    experiment in TRIALS || throw(ArgumentError("choose camu, box1, or box2"))
    relative = joinpath("data", "raw", "cocoa", "CocoaModel-master", "simulation", getproperty(DRIVERS, experiment))
    data = inspect_dataset(joinpath(root, relative))
    return merge(data, (; experiment, source_file=relative))
end

function published_summaries(; root=ROOT)
    path = joinpath(root, "data", "raw", "transcribed", "cocoa2018", "posterior_summaries.csv")
    lines = readlines(path)
    first(lines) == "experiment,parameter,mean,sd,q025,q50,q975,table,page" || error("Unexpected summary header")
    rows = map(lines[2:end]) do line
        fields = split(line, ',')
        length(fields) == 9 || error("Unexpected summary row")
        experiment, parameter = Symbol(fields[1]), Symbol(fields[2])
        numbers = parse.(Float64, fields[3:7])
        all(isfinite, numbers) && all(>=(0), numbers) || error("Invalid posterior summary")
        numbers[3] <= numbers[4] <= numbers[5] || error("Unordered posterior quantiles")
        (; experiment, parameter, mean=numbers[1], sd=numbers[2], q025=numbers[3],
            q50=numbers[4], q975=numbers[5], table=String(fields[8]), page=parse(Int, fields[9]))
    end
    expected = Set((trial, parameter) for trial in TRIALS for parameter in (COCOA_PARAMETERS..., :sigma))
    length(rows) == length(expected) && Set((r.experiment, r.parameter) for r in rows) == expected ||
        error("Incomplete or duplicate posterior summary rows")
    return rows
end

function prepare_cocoa(; root=ROOT)
    verify_cocoa(root)
    summaries = published_summaries(; root)
    destination = joinpath(root, "data", "processed", "cocoa", "moreno2018")
    mkpath(destination)
    transcription = joinpath(root, "data", "raw", "transcribed", "cocoa2018", "posterior_summaries.csv")
    inputs = Dict("posterior_summaries_sha256" => bytes2hex(open(sha256, transcription)),
        "script" => "scripts/prepare_cocoa.jl", "state_order" => collect(String.(COCOA_STATES)),
        "state_units" => "mg/g pulp", "time_units" => "h")
    for experiment in TRIALS
        data = cocoa_trial(experiment; root)
        open(joinpath(destination, "$experiment.csv"), "w") do io
            println(io, "source_id,experiment,time_h,variable,value,unit,role")
            for (t, state, role) in [(0.0, data.initial, "initial");
                [(data.times[i], data.observations[i,:], "observation") for i in eachindex(data.times)]]
                for (name, value) in zip(COCOA_STATES, state)
                    println(io, "moreno2018,$experiment,$t,$name,$value,mg/g pulp,$role")
                end
            end
        end
        tables = Dict{String,Any}()
        for row in filter(r -> r.experiment == experiment, summaries)
            name = String(row.parameter)
            units = startswith(name, "mu") || row.parameter in (:k1, :k2, :k3) ? "h^-1" : "1"
            tables[name] = Dict("value" => row.mean, "units" => units,
                "source" => "doi:10.1098/rsos.180964; doi:10.6084/m9.figshare.7152614.v2",
                "location" => "Supplement Table $(row.table), page $(row.page), Mean column; row $name",
                "confidence" => "medium",
                "notes" => "Published posterior mean rounded to three decimals, normalized coordinates; trial $experiment. " *
                    "Original fit: $(replace(data.source_file, '\\'=>'/')) and model.stan, using its embedded data. " *
                    "Transcribed in data/raw/transcribed/cocoa2018/posterior_summaries.csv; generated by scripts/prepare_cocoa.jl. " *
                    "Not a new fit or a joint posterior draw. See docs/cocoa_baseline.md for coordinate units and limitations.")
        end
        open(joinpath(root, "params", "cocoa_$(experiment)_scaled.toml"), "w") do io
            println(io, "# Generated by scripts/prepare_cocoa.jl from the published normalized posterior means.")
            TOML.print(io, tables; sorted=true)
        end
        inputs[String(experiment)] = Dict("raw_file" => replace(data.source_file, '\\'=>'/'),
            "sha256" => bytes2hex(open(sha256, joinpath(root, data.source_file))),
            "scales" => data.scales, "initial" => data.initial,
            "transformations" => "Parse numeric literals; preserve source units and values; separate fixed initial row from likelihood observations")
    end
    open(joinpath(destination, "provenance.toml"), "w") do io
        TOML.print(io, inputs; sorted=true)
    end
    println("Prepared three observation tables and sourced parameter files.")
end

end

if abspath(PROGRAM_FILE) == @__FILE__
    CocoaSourceData.prepare_cocoa()
end
